"""What each site calls its columns, and what ffanalytics calls them.

This is source_objects.R, transcribed. Every site publishes the same handful
of projections under its own headings -- "Passing Yds", "PASSING YDS", "Pass
Yds", "passingYards" -- and a scrape is only useful once they all say
`pass_yds`, so each source carries a map from its headings to the shared
names, and `rename()` (rvest's `rename_vec`) applies it, leaving anything
unlisted alone.

Four of the maps name the same heading twice, and that is deliberate rather
than a mistake to tidy up. FantasySharks calls both the passing and the
field-goal column "Att"; FFToday calls a sack "Sack" whether a defense or a
linebacker made it. R's `match()` takes the first hit, so the first line wins
and the scrape fixes up the rest afterwards -- FFToday rewrites `dst_` to
`idp_` once it knows the position. A Python dict would let the *last* line
win and quietly invert that, so those four are written as pairs and built
first-wins by `_first()`.
"""


def _first(pairs):
    """A map from (old, new) pairs, keeping the first of any repeat."""
    out = {}
    for old, new in pairs:
        out.setdefault(old, new)
    return out


def rename(names, mapping):
    """rename_vec: rename what the map knows, leave the rest as it is."""
    return [mapping.get(name, name) for name in names]


